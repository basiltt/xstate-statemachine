async def _client(base: str, n: int) -> httpx.AsyncClient:
    limits = httpx.Limits(max_connections=n, max_keepalive_connections=n)
    return httpx.AsyncClient(
        base_url=base, timeout=REQUEST_TIMEOUT, limits=limits
    )


async def _post(
    ac: httpx.AsyncClient, order: str, event: str, body: Any = None, **h: str
) -> Tuple[int, Dict[str, Any], float]:
    t0 = time.perf_counter()
    r = await ac.post(
        f"/orders/{order}/events/{event}",
        json=body,
        headers={**CUSTOMER, **h},
    )
    try:
        data = r.json()
    except ValueError:
        data = {}
    return r.status_code, data, time.perf_counter() - t0


def _classify(status: int, body: Dict[str, Any]) -> str:
    if status == 409:
        return "409"
    if status != 200:
        return f"http-{status}"
    if body.get("duplicate"):
        return "duplicate"
    return "changed" if body.get("changed") else "unchanged"


@WINDOWS_UVICORN_STALL
# -----------------------------------------------------------------------------
# 1. exactly one PAY, no stall
# -----------------------------------------------------------------------------
@pytest.mark.parametrize("with_key", [False, True])
def test_two_hundred_pays_exactly_one_charge_no_stall(
    fleet: Fleet, with_key: bool
) -> None:
    fleet.start_web()
    order = f"pay-{int(time.time() * 1000)}-{int(with_key)}"
    n = 200

    async def go() -> List[Tuple[int, Dict[str, Any], float]]:
        async with await _client(fleet.base, n) as ac:
            assert (
                await _post(ac, order, "ADD_ITEM", {"sku": "tea", "qty": 1})
            )[0] == 200
            assert (await _post(ac, order, "CHECKOUT"))[0] == 200
            headers = {"Idempotency-Key": f"pay-{order}"} if with_key else {}
            return list(
                await asyncio.gather(
                    *[
                        _post(
                            ac,
                            order,
                            "PAY",
                            {"card_token": "tok_ok"},
                            **headers,
                        )
                        for _ in range(n)
                    ]
                )
            )

    results = asyncio.run(go())
    kinds: Dict[str, int] = {}
    for status, body, _ in results:
        k = _classify(status, body)
        kinds[k] = kinds.get(k, 0) + 1
    assert set(kinds) <= {"changed", "unchanged", "duplicate", "409"}, kinds
    assert kinds.get("changed") == 1, kinds
    lat = sorted(t for _, _, t in results)
    p95 = lat[int(0.95 * len(lat)) - 1]
    # 🔥 no request may stall: the slowest of 200 must be in the same
    #    order of magnitude as p95, never the client timeout
    assert lat[-1] < REQUEST_TIMEOUT, (lat[-1], p95)
    assert lat[-1] < max(5.0, 10 * p95), (lat[-1], p95)


@WINDOWS_UVICORN_STALL
# -----------------------------------------------------------------------------
# 2. no lost update across workers
# -----------------------------------------------------------------------------
def test_hundred_adds_across_workers_converge(fleet: Fleet) -> None:
    fleet.start_web()
    order = f"add-{int(time.time() * 1000)}"

    async def go() -> Tuple[int, int]:
        async with await _client(fleet.base, 100) as ac:
            rs = await asyncio.gather(
                *[
                    _post(ac, order, "ADD_ITEM", {"sku": "tea", "qty": 1})
                    for _ in range(100)
                ]
            )
            codes = [s for s, _, _ in rs]
            assert set(codes) <= {200, 409}, codes
            retries = 0
            for _ in range(codes.count(409)):
                while True:
                    s, _, _ = await _post(
                        ac, order, "ADD_ITEM", {"sku": "tea", "qty": 1}
                    )
                    retries += 1
                    if s == 200:
                        break
                    assert s == 409
                    assert retries < 5000, "409 storm did not converge"
            final = await ac.get(f"/orders/{order}", headers=CUSTOMER)
            return len(final.json()["context"]["items"]), retries

    items, retries = asyncio.run(go())
    assert items == 100
    from xstate_statemachine.persistence import SQLiteStore

    store = SQLiteStore(fleet.env["XSM_ORDERS_DB"])
    try:
        rec = store.load(f"order.{order}")
    finally:
        store.close()
    assert rec is not None and rec.version == 100, rec


# -----------------------------------------------------------------------------
# 3. the scheduler fires once
# -----------------------------------------------------------------------------
def test_scheduler_process_fires_the_payment_timeout_once(
    fleet: Fleet,
) -> None:
    """`awaitingPayment` has a 15-minute `after` → `expired`. The chart
    reads the delay from the `delays` map when the app sets
    ``XSM_PAYMENT_TIMEOUT_MS``; the web workers never fire timers -- only
    the scheduler process does, exactly once."""
    fleet.env["XSM_PAYMENT_TIMEOUT_MS"] = "1500"
    fleet.start_web()
    order = f"exp-{int(time.time() * 1000)}"

    async def arm() -> None:
        async with await _client(fleet.base, 4) as ac:
            assert (
                await _post(ac, order, "ADD_ITEM", {"sku": "tea", "qty": 1})
            )[0] == 200
            assert (await _post(ac, order, "CHECKOUT"))[0] == 200

    asyncio.run(arm())
    # web workers alone: reads for 3 s never flip the state
    deadline = time.monotonic() + 3.0
    while time.monotonic() < deadline:
        r = httpx.get(f"{fleet.base}/orders/{order}", headers=CUSTOMER)
        assert r.json()["state"] == "awaitingPayment", r.json()
        time.sleep(0.25)
    fleet.start_scheduler(interval_s=0.2)
    deadline = time.monotonic() + 20.0
    state = None
    while time.monotonic() < deadline:
        state = httpx.get(
            f"{fleet.base}/orders/{order}", headers=CUSTOMER
        ).json()["state"]
        if state == "expired":
            break
        time.sleep(0.25)
    assert state == "expired"
    # fired exactly once: one `expired` transition in the audit of versions
    from xstate_statemachine.persistence import SQLiteStore

    store = SQLiteStore(fleet.env["XSM_ORDERS_DB"])
    try:
        rec = store.load(f"order.{order}")
        due = list(store.due_keys(time.time() + 10_000))
    finally:
        store.close()
    assert rec is not None and rec.version == 3, rec  # ADD, CHECKOUT, expire
    assert f"order.{order}" not in due  # deadline consumed, not re-armed


@WINDOWS_UVICORN_STALL
# -----------------------------------------------------------------------------
# 4. rolling restart
# -----------------------------------------------------------------------------
def test_rolling_restart_keeps_the_store_consistent(fleet: Fleet) -> None:
    fleet.start_web()
    order = f"rr-{int(time.time() * 1000)}"

    async def phase(n: int) -> None:
        async with await _client(fleet.base, 20) as ac:
            rs = await asyncio.gather(
                *[
                    _post(ac, order, "ADD_ITEM", {"sku": "tea", "qty": 1})
                    for _ in range(n)
                ]
            )
            for s, _, _ in rs:
                assert s in (200, 409)
                if s == 409:
                    while (
                        await _post(
                            ac, order, "ADD_ITEM", {"sku": "tea", "qty": 1}
                        )
                    )[0] != 200:
                        pass

    asyncio.run(phase(20))
    assert httpx.get(f"{fleet.base}/_xsm/ready").status_code == 200
    loadtest.stop_server(fleet.web)
    fleet.web = None
    with pytest.raises(httpx.HTTPError):
        httpx.get(f"{fleet.base}/_xsm/ready", timeout=2.0)
    fleet.start_web()
    assert httpx.get(f"{fleet.base}/_xsm/ready").status_code == 200
    asyncio.run(phase(20))
    final = httpx.get(f"{fleet.base}/orders/{order}", headers=CUSTOMER).json()
    assert len(final["context"]["items"]) == 40


