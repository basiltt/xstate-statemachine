"""#277 battle: the multi-worker claims, run against REAL worker processes.

Every other test in this directory drives the app in-process. The guide
and README make claims about ``uvicorn --workers 4`` plus one
``--role scheduler`` process -- separate OS processes sharing only the
store -- and those claims are what a FastAPI developer acts on. So this
module spawns the processes (`loadtest.py`'s launcher: no fork, polls
`/_xsm/health`) and checks:

* **exactly one PAY** across 4 workers × 200 concurrent requests, with
  and without a shared `Idempotency-Key`; only `200` / `409`; p95 within
  a generous bound and NO request stalling (a 60 s client timeout was
  seen once in five runs of the committed load test -- a stall is a
  defect, not noise);
* **no lost update** across workers: 100 `ADD_ITEM`s to one order from 4
  workers converge to 100 items after client-side 409 retries, and the
  stored version equals the successful sends;
* **the scheduler fires once**: an `after` deadline (payment timeout,
  shortened via the chart's `delays`) is woken by the separate scheduler
  process exactly once while 4 web workers keep serving reads; the
  web workers never fire it themselves;
* **readiness under rolling restart**: killing and restarting the web
  supervisor leaves the store consistent; `/_xsm/ready` is 503 while a
  worker drains and 200 after;
* **the README's numbers** are regenerated by this run and must agree in
  shape with what the README states (one changed receipt; the rest
  unchanged / duplicate / 409).

Skipped unless `uvicorn` is importable; runs with SQLite in a temp dir.
Set ``XSM_BATTLE_277_WORKERS`` to change the worker count (default 4).
"""

