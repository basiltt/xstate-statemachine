def _new(eng: Any) -> int:
    with Session(eng) as s:
        t = Thing()
        s.add(t)
        s.commit()
        return t.id


def _send(eng: Any, tid: int, event: str, **payload: Any) -> None:
    with Session(eng) as s:
        s.get(Thing, tid).send(event, session=s, **payload)
        s.commit()


def _ids_in(eng: Any, *sids: str) -> list:
    with Session(eng) as s:
        return list(s.scalars(select(Thing.id).where(Thing.in_state(*sids))))


