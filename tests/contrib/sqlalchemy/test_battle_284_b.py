def test_non_json_context_values_are_stringified(engine: Any) -> None:
    """Pins today's core behaviour (`get_snapshot` uses ``default=str``):
    a datetime / Decimal / set survives a save as its ``str()``. Loud
    would be better; it is core-wide, not [sqlalchemy]-specific."""
    import datetime
    import decimal

    tid = _new(engine)
    for v in (datetime.date(2026, 1, 2), decimal.Decimal("1.50"), {7}):
        _send(engine, tid, "PUT", v=v)
        with Session(engine) as s:
            assert s.get(Thing, tid).machine.context["v"] == str(v)


