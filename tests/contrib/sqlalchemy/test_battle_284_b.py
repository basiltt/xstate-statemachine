# 5. in_state() escaping
# -----------------------------------------------------------------------------
def test_in_state_treats_underscore_and_percent_literally(engine: Any):
    a = _new(engine)
    _send(engine, a, "PUT", v=1)  # m_1.a_b
    b = _new(engine)
    _send(engine, b, "GO")  # m_1.pct%
    assert _ids_in(engine, "m_1.a_b") == [a]
    assert _ids_in(engine, "m_1.axb") == []  # `_` is not a wildcard
    assert _ids_in(engine, "m_1.a%") == []  # `%` is not a wildcard
    assert _ids_in(engine, "m_1.pct%") == [b]
    assert _ids_in(engine, "m_1.pctX") == []
    assert _ids_in(engine, "m_1.pct") == []
    assert _ids_in(engine, "m_1") == [a, b]  # ancestor
    assert _ids_in(engine, "m_") == []
    assert sorted(_ids_in(engine, "m_1.a_b", "m_1.pct%")) == [a, b]


