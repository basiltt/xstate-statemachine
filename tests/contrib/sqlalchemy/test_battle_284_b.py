def _alembic(url: str, script_dir: Path) -> Any:
    from alembic.config import Config

    cfg = Config(str(EXAMPLE / "alembic.ini"))
    cfg.set_main_option("script_location", str(script_dir))
    cfg.set_main_option("sqlalchemy.url", url)
    cfg.attributes["configure_logger"] = False
    return cfg


@pytest.fixture
def example_models() -> Iterator[Any]:
    """The example's `models`, imported from ITS directory and left in
    `sys.modules` for the test (env.py's `from models import Base` must
    bind the SAME metadata object the test mutates); another example's
    same-named modules (fastapi_orders, flask_wizard -- CI's Coverage job
    runs them all in one process) are set aside and restored after."""
    import importlib

    names = ("logic", "models")
    saved = {k: sys.modules.pop(k) for k in names if k in sys.modules}
    sys.path.insert(0, str(EXAMPLE))
    try:
        importlib.import_module("logic")
        models = importlib.import_module("models")
        yield models
    finally:
        sys.path.remove(str(EXAMPLE))
        for k in names:
            sys.modules.pop(k, None)
        sys.modules.update(saved)


def _diff(url: str, metadata: Any) -> list:
    from alembic.autogenerate import compare_metadata
    from alembic.migration import MigrationContext

    eng = create_engine(url)
    try:
        with eng.connect() as conn:
            return compare_metadata(MigrationContext.configure(conn), metadata)
    finally:
        eng.dispose()


def test_alembic_upgrade_no_diff_second_migration_downgrade(
    url: str, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, example_models
) -> None:
    pytest.importorskip("alembic")
    from alembic import command
    from sqlalchemy import Column, String

    monkeypatch.setenv("ORDERS_DB_URL", url)
    mig = tmp_path / "migrations"
    shutil.copytree(
        EXAMPLE / "migrations",
        mig,
        ignore=shutil.ignore_patterns("__pycache__"),
    )
    models = example_models
    cfg = _alembic(url, mig)
    command.upgrade(cfg, "head")
    eng = create_engine(url)
    try:
        cols = {c["name"]: c for c in inspect(eng).get_columns("orders")}
        kind = type(cols["statechart"]["type"]).__name__
        assert kind == ("JSONB" if url.startswith("postgresql") else "JSON")
        # 🔥 the outbox store creating its table must not make a diff
        store = SQLAlchemyStore(sessionmaker(eng), metadata=MetaData())
        SQLAlchemyOutboxStore(store)
    finally:
        eng.dispose()
    assert _diff(url, models.Base.metadata) == []
    # -- the team's next migration: a column on orders, autogenerated
    orders = models.Base.metadata.tables["orders"]
    orders.append_column(Column("coupon", String(40), nullable=True))
    try:
        command.revision(cfg, "coupon", autogenerate=True, rev_id="0004")
        [new] = list((mig / "versions").glob("0004_*.py"))
        body = new.read_text("utf-8")
        assert "add_column" in body and "coupon" in body
        assert "drop_table" not in body and "alter_column" not in body
        command.upgrade(cfg, "head")
        assert _diff(url, models.Base.metadata) == []
        command.downgrade(cfg, "0003")
    finally:
        orders._columns.remove(orders.c.coupon)
    assert _diff(url, models.Base.metadata) == []
    command.downgrade(cfg, "base")
    eng = create_engine(url)
    try:
        assert set(inspect(eng).get_table_names()) <= {"alembic_version"}
    finally:
        eng.dispose()


