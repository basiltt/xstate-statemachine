def test_wide_parallel_state_round_trips(engine: Any, url: str) -> None:
    tid = _new(engine)
    _send(engine, tid, "GO")
    try:
        _send(engine, tid, "WIDE")
    except Exception as exc:  # 🔥 Postgres: StringDataRightTruncation
        if not url.startswith("postgresql"):
            raise
        pytest.xfail(
            "mixin.py (adversary A): statechart_state is String(512); "
            f"Postgres refuses a wide parallel chart ({type(exc).__name__})"
            ", SQLite stores it -- make it Text"
        )
    with Session(engine) as s:
        row = s.get(Thing, tid)
        assert len(row.state) > 512
        assert len(row.statechart_state_ids) == WIDE
    assert _ids_in(engine, "m_1.wide") == [tid]


def test_raw_insert_of_schema_row_roundtrip(engine: Any) -> None:
    tables = build_tables(MetaData())
    with engine.begin() as conn:
        ensure_schema(conn, tables)
        ensure_schema(conn, tables)  # idempotent
        n = conn.execute(select(tables.schema.c.version)).all()
    assert n == [(SCHEMA_VERSION,)]
    with engine.begin() as conn:
        with pytest.raises(Exception):
            conn.execute(
                insert(tables.schema).values(component="sqlalchemy", version=1)
            )


