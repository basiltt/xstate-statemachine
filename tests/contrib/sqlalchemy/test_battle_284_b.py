def _put(i: Any, ctx: Dict[str, Any], e: Any, a: Any) -> None:
    ctx["v"] = e.payload.get("v")


def _chart() -> Dict[str, Any]:
    leaf = "leaf_" + "y" * 40
    regions = {
        f"r{n:02d}_" + "x" * 30: {"initial": leaf, "states": {leaf: {}}}
        for n in range(WIDE)
    }
    return {
        "id": "m_1",
        "initial": "a_b",
        "context": {"v": None},
        "states": {
            "a_b": {"on": {"PUT": {"actions": "put"}, "GO": "pct%"}},
            "axb": {},
            "pct%": {"on": {"WIDE": "wide"}},
            "pctX": {},
            "wide": {"type": "parallel", "states": regions},
        },
    }


class Base(DeclarativeBase):
    pass


class Thing(StatechartMixin, Base):
    __tablename__ = "b284b_things"
    __xsm_machine__ = create_machine(
        _chart(), logic=MachineLogic(actions={"put": _put})
    )
    id: Mapped[int] = mapped_column(primary_key=True)
    statechart: Mapped[Optional[Dict[str, Any]]] = mapped_column(
        StatechartType(max_snapshot_bytes=CAP), nullable=True
    )
    __mapper_args__ = StatechartMixin.optimistic()


xsm_sqlalchemy_ddl(Base.metadata)


