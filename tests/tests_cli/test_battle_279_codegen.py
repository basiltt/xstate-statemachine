# 4. odd names
# -----------------------------------------------------------------------------
def test_odd_event_names_slug_uniquely_or_are_refused(
    tmp_path: pathlib.Path,
) -> None:
    from fastapi import FastAPI

    cfg = {
        "id": "odd",
        "initial": "a",
        "states": {
            "a": {
                "on": {
                    "with space": "a",
                    "colon:sep": "a",
                    "bang!": "a",
                    "slash/sep": "a",
                    "éclair": "a",
                    "ORDER.PAID": "a",
                    "ORDER_PAID": "a",
                }
            }
        },
    }
    src = tmp_path / "odd.json"
    src.write_text(json.dumps(cfg), encoding="utf-8")
    code, text = _gen(src, tmp_path, "-f")
    assert code == 0, text
    mod = _import_fresh(tmp_path, "odd_api")
    app = FastAPI()
    app.include_router(mod.router)
    doc = app.openapi()
    routes = [p for p in doc["paths"] if "/events/" in p]
    assert len(routes) == 7, routes
    ops = [
        op["operationId"] for p in routes for op in doc["paths"][p].values()
    ]
    assert len(ops) == len(set(ops)), ops
    assert all(o.isascii() for o in ops), ops
    # two events that slug to the SAME identifier keep DISTINCT routes
    # (the raw slugs differ) and unique operationIds -- never merged
    cfg["states"]["a"]["on"] = {"pay now": "a", "pay-now": "a"}
    src.write_text(json.dumps(cfg), encoding="utf-8")
    code, text = _gen(src, tmp_path, "-f")
    assert code == 0, text
    mod = _import_fresh(tmp_path, "odd_api")
    app = FastAPI()
    app.include_router(mod.router)
    doc = app.openapi()
    routes = sorted(
        p for p in doc["paths"] if "/events/" in p and "{event}" not in p
    )
    assert len(routes) == 2, routes
    ops = [
        op["operationId"] for p in routes for op in doc["paths"][p].values()
    ]
    assert len(set(ops)) == 2, ops


