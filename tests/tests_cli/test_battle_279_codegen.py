def _run(argv: List[str]) -> Tuple[int, str]:
    saved, sys.argv = sys.argv, ["xsm", *argv]
    buf = io.StringIO()
    logging.disable(logging.CRITICAL)
    try:
        with redirect_stdout(buf):
            main()
        code = 0
    except SystemExit as exc:
        code = int(exc.code or 0)
    finally:
        sys.argv = saved
        logging.disable(logging.NOTSET)
    return code, buf.getvalue()


def _module(cfg_path: pathlib.Path) -> str:
    cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    raw = str(cfg.get("id", cfg_path.stem)).replace(" ", "_")
    return module_safe_name(camel_to_snake(raw))


def _gen(src: pathlib.Path, out: pathlib.Path, *extra: str) -> Tuple[int, str]:
    return _run(
        [
            "gt",
            str(src),
            "-t",
            "pythonic-class",
            "--with-api",
            "--with-models",
            "-o",
            str(out),
            "--plain",
            *extra,
        ]
    )


def _strip_banner(text: str) -> str:
    return "\n".join(
        ln
        for ln in text.splitlines()
        if not ln.startswith("# Generated by")
        and "xstate-statemachine " not in ln
    )


def _import_fresh(out: pathlib.Path, name: str) -> Any:
    # 📝 charts sharing an `id` generate the same module names; evict every
    #    generated module so `<x>_api` never binds a stale `<x>_models`
    for mod in [m for m in sys.modules if m.endswith(("_api", "_models"))]:
        sys.modules.pop(mod, None)
    importlib.invalidate_caches()
    if str(out) not in sys.path:
        sys.path.insert(0, str(out))
    try:
        return importlib.import_module(name)
    finally:
        sys.path.remove(str(out))


