# 3. the generated router keeps the registry's rules
# -----------------------------------------------------------------------------
def test_generated_router_denial_saves_nothing_and_stub_raises(
    tmp_path: pathlib.Path,
) -> None:
    from fastapi import FastAPI
    from fastapi.testclient import TestClient

    # 📝 the generated module imports the INSTALLED package name; the
    #    registry / exception classes must be the same objects (two copies
    #    of the package would make `instrument_app`'s handler miss)
    from xstate_statemachine import create_machine, stub_logic
    from xstate_statemachine.contrib.fastapi import instrument_app

    src = CORPUS / "AdvancePayment.json"
    assert _gen(src, tmp_path, "-f")[0] == 0
    api = _import_fresh(tmp_path, _module(src) + "_api")
    cfg = json.loads(src.read_text("utf-8"))
    machine = create_machine(cfg, logic=stub_logic(cfg))
    # X0.1: the stub refuses until implemented
    with pytest.raises(NotImplementedError):
        api.authorize(None, name="x", key="k", event=None)

    def authorize(conn: Any, *, name: str, key: str, event: Any) -> bool:
        return event != "RETRY"

    api.register(machine, authorize=authorize)
    app = FastAPI()
    app.include_router(api.router)
    instrument_app(app, api.registry)
    base = f"/{api.MACHINE_NAME}/k"
    # 📝 the denial is RAISED and mapped by instrument_app's handler; the
    #    TestClient re-raises handled server exceptions unless told not to
    with TestClient(app, raise_server_exceptions=False) as c:
        assert c.get(base).status_code == 200
        r = c.post(f"{base}/events/SUBMIT", json={})
        assert r.status_code == 200 and r.json()["state"] == "challenge"
        skey = api.registry.store_key(api.MACHINE_NAME, "k")
        v1 = api.registry.store.load(skey).version
        r = c.post(f"{base}/events/RETRY", json={})
        assert r.status_code == 403
        # 🔥 a refused request must not save: the version is unchanged
        assert api.registry.store.load(skey).version == v1
        assert c.post(f"{base}/events/NOPE", json={}).status_code == 404
        r = c.post(
            f"{base}/events/SUBMIT", json={}, headers={"Idempotency-Key": "x"}
        )
        assert r.status_code == 501


