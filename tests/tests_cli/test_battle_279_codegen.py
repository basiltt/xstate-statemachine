def test_whole_corpus_generates_parses_imports_mounts(
    tmp_path: pathlib.Path,
) -> None:
    """Every corpus chart (~2.5 min in-process) when ``XSM_FULL_CORPUS=1``
    (the Linux 3.14 CI cell and the battle gates); a deterministic
    12-chart sample -- including the id-colliding and the refused ones --
    on every other run (review M1: the full pass added 2.5 min to every
    cell of the matrix)."""
    import os

    from fastapi import FastAPI

    charts = sorted(CORPUS.glob("*.json"))
    if os.environ.get("XSM_FULL_CORPUS") != "1":
        must = {"emailProcessing.json", "debt.json", "APA_Logic.json"}
        picked = [c for c in charts if c.name in must]
        picked += [c for c in charts if c.name not in must][::9]
        charts = sorted(set(picked))[:12]
        # keep one id collision in the sample
        debt = [
            c
            for c in sorted(CORPUS.glob("*.json"))
            if "debt" in c.name.lower()
        ]
        charts = sorted(set(charts) | set(debt[:2]))
    refused: Dict[str, str] = {}
    by_module: Dict[str, List[str]] = {}
    for src in charts:
        out = tmp_path / src.stem
        out.mkdir()
        code, text = _gen(src, out, "-f")
        if code != 0:
            refused[src.name] = (
                text.strip().splitlines()[-1][:120] if text else ""
            )
            continue
        api = list(out.glob("*_api.py"))
        assert len(api) == 1, (src.name, sorted(p.name for p in out.iterdir()))
        by_module.setdefault(api[0].stem, []).append(src.name)
        for f in list(out.glob("*_api.py")) + list(out.glob("*_models.py")):
            ast.parse(f.read_text("utf-8"), filename=str(f))
        mod = _import_fresh(out, api[0].stem)
        app = FastAPI()
        app.include_router(mod.router)
        doc = app.openapi()
        cfg = json.loads(src.read_text("utf-8"))
        from src.xstate_statemachine.contrib.starlette._http import (
            declared_events,
        )
        from src.xstate_statemachine import create_machine, stub_logic

        machine = create_machine(cfg, logic=stub_logic(cfg))
        want = len(declared_events(machine))
        got = sum(1 for p in doc["paths"] if "/events/" in p)
        assert got == want, (src.name, got, want)
    # the deliberate refusals are the known ones, each with a reason
    assert set(refused) <= {"emailProcessing.json"}, refused
    for name, reason in refused.items():
        assert reason, name
    # charts whose ids collide produce the same filename
    collisions = {m: v for m, v in by_module.items() if len(v) > 1}
    assert collisions, "the sample must contain an id collision"


def test_colliding_module_names_are_reported_by_check(
    tmp_path: pathlib.Path,
) -> None:
    """Two corpus charts with the same `id` write the same `_api.py`; the
    second overwrote the first silently. `--check` after the second must
    say the file on disk is NOT the first chart's output."""
    a = CORPUS / "debt.json"
    others = [
        p
        for p in sorted(CORPUS.glob("*.json"))
        if p != a
        and json.loads(p.read_text("utf-8")).get("id")
        == json.loads(a.read_text("utf-8")).get("id")
    ]
    assert others, "no second chart with the same id"
    b = others[0]
    assert _gen(a, tmp_path, "-f")[0] == 0
    assert _gen(b, tmp_path, "-f")[0] == 0
    code, text = _gen(a, tmp_path, "--check")
    assert code == 1, text  # a's output was overwritten by b's
    assert "out of date" in text


