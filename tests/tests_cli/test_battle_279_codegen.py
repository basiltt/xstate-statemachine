"""#279 battle: the codegen companions a team checks in and edits.

`xsm gt --with-api --with-models` emits a FastAPI router and pydantic
models a team owns. Those files are a verified STARTING POINT -- so what
is verified must be true for every chart, the output must be stable
under regeneration, and the generated router must have the registry's
guarantees, not a lookalike. Pinned, in-process (no 2.4 s subprocess per
chart):

* **the whole corpus** -- every chart that generates yields `_api.py` /
  `_models.py` that `ast.parse`, import, mount on a `FastAPI()` and
  produce an OpenAPI document with one route per declared event (the
  deliberate refusals -- a chart with no states -- are named, not
  silent); charts whose ids collide produce the same filename, which
  `--check` must report rather than silently overwrite;
* **byte-stable regeneration** -- generating twice is identical (modulo
  the provenance banner's timestamp/version line), `--check` is exit 0,
  adding an event flips `--check` to 1 and `--diff` names the route;
* **the generated router keeps the registry's rules** -- a per-event
  `authorize` denial is a 403 that saves NOTHING (the version does not
  bump; a refused request must not make a concurrent writer lose with
  409), `Idempotency-Key` without an inbox is 501, an unknown event
  route is 404, the `authorize` stub RAISES until implemented (X0.1);
* **odd names** -- event types with spaces / `:` / `!` / `/` / unicode
  slug into unique URL segments and unique `operationId`s; two events
  that slug identically are refused at generation, not merged;
* **Windows** -- an output directory with spaces and unicode; CRLF-safe
  files; `--plain` output has no mojibake;
* **performance** -- in-process generation of a 50-event chart in
  bounded time; `--check` over the corpus does not re-import or
  re-verify when nothing changed.
"""

