def test_fifty_event_chart_generates_in_bounded_time(
    tmp_path: pathlib.Path,
) -> None:
    cfg = {
        "id": "wide",
        "initial": "a",
        "states": {"a": {"on": {f"E{n}": "a" for n in range(50)}}},
    }
    src = tmp_path / "wide.json"
    src.write_text(json.dumps(cfg), encoding="utf-8")
    t0 = time.perf_counter()
    code, text = _gen(src, tmp_path, "-f")
    took = time.perf_counter() - t0
    assert code == 0, text
    assert took < 20.0, took
    t0 = time.perf_counter()
    code, text = _gen(src, tmp_path, "--check")
    assert code == 0 and time.perf_counter() - t0 < 20.0
