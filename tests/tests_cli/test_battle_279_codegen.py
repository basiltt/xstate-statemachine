def test_regeneration_is_byte_stable_and_check_detects_drift(
    tmp_path: pathlib.Path,
) -> None:
    src = tmp_path / "pay.json"
    cfg = json.loads((CORPUS / "AdvancePayment.json").read_text("utf-8"))
    src.write_text(json.dumps(cfg), encoding="utf-8")
    assert _gen(src, tmp_path, "-f")[0] == 0
    first = {
        f.name: _strip_banner(f.read_text("utf-8"))
        for f in tmp_path.glob("*.py")
    }
    time.sleep(1.1)  # a banner timestamp, if any, moves
    assert _gen(src, tmp_path, "-f")[0] == 0
    second = {
        f.name: _strip_banner(f.read_text("utf-8"))
        for f in tmp_path.glob("*.py")
    }
    assert first == second
    code, text = _gen(src, tmp_path, "--check")
    assert code == 0 and "up to date" in text
    cfg["states"]["challenge"]["on"]["NUDGE"] = {"target": "challenge"}
    src.write_text(json.dumps(cfg), encoding="utf-8")
    code, text = _gen(src, tmp_path, "--check")
    assert code == 1 and "out of date" in text
    code, text = _gen(src, tmp_path, "--diff")
    assert code == 1 and "/events/NUDGE" in text


